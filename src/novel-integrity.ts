/**
 * Independent completeness gate for third-party novel downloads.
 *
 * The engine (so-novel) reports success even when a chapter was dropped or a
 * paginated chapter only returned its first page. This module therefore trusts
 * only the downloaded artifacts plus an independently parsed catalog, and it
 * never mutates or imports anything. A download may enter the shelf only when
 * `assessNovelDownload` returns `complete: true` with no issues.
 *
 * Kept free of I/O so the same rules can later run in the World, in a worker,
 * or in an offline acceptance harness.
 */

export interface CatalogChapter {
  order: number;
  title: string;
  url: string;
}

export interface DownloadChapterFile {
  /** Parsed order from the `NNN_title.txt` file name. */
  order: number;
  /** Parsed title from the file name (may be sanitized). */
  title: string;
  /** Raw TXT generated by the engine, including its first title line. */
  text: string;
}

export interface NovelIdentity {
  title: string;
  author: string;
  sourceId: number;
  sourceName: string;
  bookUrl: string;
}

export interface NovelIntegrityInput {
  book: NovelIdentity;
  catalog: CatalogChapter[];
  files: DownloadChapterFile[];
  /** Catalog re-parsed after the download. Any change rejects the snapshot. */
  catalogAfter?: CatalogChapter[];
  /** Stop after catalog checks; used to reject mixed editions before downloading. */
  catalogOnly?: boolean;
  options?: {
    minChapterChars?: number;
    /** Titles whose numbers restart are legitimate only for explicit volumes. */
    allowNonMonotonicNumbers?: boolean;
  };
}

export type NovelIntegrityIssueCode =
  | 'missing_identity'
  | 'catalog_empty'
  | 'catalog_too_large'
  | 'catalog_order_gap'
  | 'catalog_duplicate_order'
  | 'catalog_duplicate_url'
  | 'catalog_duplicate_title'
  | 'catalog_duplicate_number'
  | 'catalog_number_regression'
  | 'catalog_number_order_mismatch'
  | 'catalog_volume_restart'
  | 'catalog_title_alias'
  | 'source_fallback'
  | 'catalog_changed'
  | 'missing_chapter'
  | 'unexpected_chapter_file'
  | 'catalog_title_encoding'
  | 'catalog_announcement'
  | 'duplicate_chapter_file'
  | 'empty_chapter'
  | 'source_empty_chapter'
  | 'short_chapter'
  | 'placeholder_chapter'
  | 'duplicate_chapter_body'
  | 'missing_page_marker'
  | 'truncated_chapter_tail'
  | 'page_probe_missing_page'
  | 'page_probe_short'
  | 'page_probe_unavailable';

export interface NovelIntegrityIssue {
  code: NovelIntegrityIssueCode;
  message: string;
  chapter?: number;
}

export interface NovelIntegrityResult {
  complete: boolean;
  /** Blocking issues. A non-empty list always means complete=false. */
  issues: NovelIntegrityIssue[];
  /** Non-blocking catalog-number problems accepted under the small-typo policy. */
  warnings: NovelIntegrityIssue[];
  /** Sorted, de-duplicated chapter bodies in catalog order (only when complete). */
  chapters: Array<{ order: number; title: string; text: string }>;
  totalChars: number;
}

const DEFAULT_MIN_CHAPTER_CHARS = 40;
const MAX_CATALOG_CHAPTERS = 5000;

const STRONG_PAGINATION = /(本章未完|点击下一页|點擊下一頁|请点击下一页|請點擊下一頁|翻页继续|翻頁繼續)/u;
const NEXT_PAGE_WORD = /(上一页|下一页|上一頁|下一頁)/u;
const PAGE_COUNTER = /第\s*[（(]?\s*\d+\s*[/／]\s*\d+\s*[)）]?\s*页/u;
const PLACEHOLDER = /(章节内容加载失败|章节不存在|章节已删除|内容正在手打|正在手打中|请稍后再试|请稍候|无内容|404\s*not\s*found|error\s*404)/iu;
const TRUNCATING_TAIL = /[，,、；;：:（(【[《]$/u;
const CN_DIGITS: Record<string, number> = {
  '零': 0, '〇': 0, '一': 1, '二': 2, '两': 2, '三': 3, '四': 4,
  '五': 5, '六': 6, '七': 7, '八': 8, '九': 9,
};
const CN_UNITS: Record<string, number> = { '十': 10, '百': 100, '千': 1000 };

/** Parse `第001回`, `第一百二十回`, `第12章`, `第十二节`; null when absent. */
export function chapterNumberOf(title: string): number | null {
  const arabic = title.match(/第\s*0*(\d{1,6})\s*[回章节卷篇]/u);
  if (arabic) {
    const value = Number(arabic[1]);
    return Number.isSafeInteger(value) && value > 0 ? value : null;
  }
  const chinese = title.match(/第\s*([零〇一二两三四五六七八九十百千]{1,12})\s*[回章节卷篇]/u);
  if (!chinese) return null;
  return chineseToNumber(chinese[1]);
}

function chineseToNumber(text: string): number | null {
  let total = 0;
  let section = 0;
  let digit = 0;
  let saw = false;
  for (const char of text) {
    if (char in CN_DIGITS) {
      digit = CN_DIGITS[char];
      saw = true;
    } else if (char === '万') {
      total += (section + digit) * 10000;
      section = 0;
      digit = 0;
      saw = true;
    } else if (char in CN_UNITS) {
      const unit = CN_UNITS[char];
      section += (digit || 1) * unit;
      digit = 0;
      saw = true;
    } else {
      return null;
    }
  }
  if (!saw) return null;
  const value = total + section + digit;
  return Number.isSafeInteger(value) && value > 0 ? value : null;
}

function chapterPart(title: string): string {
  const match = title.match(/[（(]\s*([一二三四五六七八九十百0-9]+|[上中下])\s*[)）]\s*[!！。.…]*$/u);
  return match ? match[1]! : '';
}

/**
 * A catalog title may carry an explicit volume prefix:
 *   "七星鲁王 第一章 血尸" -> 七星鲁王
 *   "云顶天宫（上） 第一章 ..." -> 云顶天宫(上)
 * Titles that start directly with a chapter marker have no explicit volume.
 */
function volumeLabel(title: string): string {
  const match = title.match(/^(.*?)\s*第\s*[0-9零〇一二两三四五六七八九十百千]{1,12}\s*[章节回]/u);
  if (!match) return '';
  const raw = match[1].trim();
  if (!raw || raw.length > 40 || /^[0-9零〇一二两三四五六七八九十百千]+$/u.test(raw)) return '';
  return raw.normalize('NFKC').replace(/\s+/gu, '').replace(/[·:：,，、]/gu, '').replace(/(?:篇|卷|部)$/u, '');
}

function normalizedTitle(title: string): string {
  return title.replace(/\s+/g, '').replace(/[_—·,，。.、:：;；!！?？'"“”‘’()（）\[\]【】]/g, '').toLowerCase();
}

/** Remove a leading 第N章/回/节 marker so a catalog title and a page heading can be compared. */
function titleWithoutChapterMarker(title: string): string {
  return normalizedTitle(title).replace(/^第[0-9零〇一二两三四五六七八九十百千]{1,12}[章节回篇]/u, '');
}

function isTitleAlias(catalogTitle: string, fileTitle: string): boolean {
  const catalog = titleWithoutChapterMarker(catalogTitle);
  const file = titleWithoutChapterMarker(fileTitle);
  return catalog.length > 0 && catalog === file;
}

/**
 * Author notes, leave notices, thanks, lottery/merch announcements and
 * volume-end markers. A social title without a chapter number is common in
 * these sources and must not be counted as a chapter: it breaks numbering and
 * would otherwise be imported as body text.
 */
const ANNOUNCEMENT_ENTRY = /(?:请假|请[^。！？]{0,6}假|请个假|请病假|病假|停更|断更|无更|今天不更|今晚不更|休息|调整作息|调整状态|恢复更新|推迟|延期|延时|更新时间|更新说明|更新调整|单章|公告|通知|感言|上架|新书|已发|周年|两周年|三周年|后记|作者的话|求票|求月票|求推荐票|求订阅|求收藏|求打赏|拉票|月票|推荐票|打赏|加更|补更|感谢|谢谢|鸣谢|致谢|中奖|抽奖|名单|活动|福利|周边|实体|卷终|卷尾|结卷|新年|春节|中秋|国庆|端午|元旦|元宵|七夕|圣诞|除夕|冬至|安康|快乐|抱歉|感冒|病倒|发烧|停电|感想|总结|说明|注意|修改|台历|卡牌|发布|微调|稍晚|回应|后续安排|(?:晚点|明天|今晚|稍后|马上|今天|这两天).{0,4}更新|(?:^|\s)ps(?:\s|$))/u;

/**
 * Whether a catalog entry is a non-story announcement rather than a chapter.
 *
 * Conservative by construction: a numbered title is never an announcement, and
 * real extra chapters (楔子/序章/番外/大结局…) carry no announcement keyword and
 * are kept. Only short, unnumbered titles that are pure symbols or carry an
 * explicit announcement keyword qualify. "番外说明" is a note and is skipped;
 * "番外 雪夜" is content and is kept.
 */
export function isAnnouncementTitle(title: string): boolean {
  const trimmed = title.trim();
  if (!trimmed || chapterNumberOf(trimmed) !== null) return false;
  // Some sources spell numbers the parser cannot value (第一一〇章 ends in 〇).
  // A title that still carries a chapter marker is a chapter, never a note.
  if (/第\s*[0-9零〇一二两三四五六七八九十百千]+\s*[回章节卷篇]/u.test(trimmed)) return false;
  const compact = trimmed.replace(/\s+/gu, '');
  if (compact.length > 30) return false;
  // Emoji-only / punctuation-only titles are notes, never chapter headings.
  if (/^[\p{P}\p{S}\p{M}\s]+$/u.test(trimmed)) return true;
  return ANNOUNCEMENT_ENTRY.test(compact);
}

function issue(code: NovelIntegrityIssueCode, message: string, chapter?: number): NovelIntegrityIssue {
  return { code, message, ...(chapter === undefined ? {} : { chapter }) };
}

function sameCatalog(left: CatalogChapter[], right: CatalogChapter[]): boolean {
  if (left.length !== right.length) return false;
  return left.every((chapter, index) => chapter.order === right[index]!.order && chapter.title === right[index]!.title && chapter.url === right[index]!.url);
}

/**
 * Evaluate whether a downloaded book is a complete, single-edition body.
 * Every rule is conservative: suspicious input fails closed instead of being
 * accepted with a warning.
 */
export function assessNovelDownload(input: NovelIntegrityInput): NovelIntegrityResult {
  const issues: NovelIntegrityIssue[] = [];
  const warnings: NovelIntegrityIssue[] = [];
  const numberIssues: NovelIntegrityIssue[] = [];
  let duplicateNumberCount = 0;
  let regressionCount = 0;
  let orderNumberMismatch = false;
  const minChapterChars = input.options?.minChapterChars ?? DEFAULT_MIN_CHAPTER_CHARS;
  const book = input.book ?? ({} as NovelIdentity);
  if (typeof book.title !== 'string' || !book.title.trim() || typeof book.author !== 'string' || !book.author.trim() ||
      !Number.isSafeInteger(book.sourceId) || typeof book.sourceName !== 'string' || !book.sourceName.trim() ||
      typeof book.bookUrl !== 'string' || !/^https?:\/\//u.test(book.bookUrl)) {
    issues.push(issue('missing_identity', 'Book title, author, source and URL must all be present'));
  }

  const catalog = Array.isArray(input.catalog) ? input.catalog : [];
  if (!catalog.length) issues.push(issue('catalog_empty', 'Catalog is empty'));
  if (catalog.length > MAX_CATALOG_CHAPTERS) issues.push(issue('catalog_too_large', `Catalog exceeds ${MAX_CATALOG_CHAPTERS} chapters`));

  // Announcement entries are not chapters: they carry no story text, repeat
  // titles ("请假一天。" several times) and shift the order/number alignment.
  // Drop them from every chapter check and from the imported text, but keep
  // their presence visible as a warning.
  const announcements = catalog.filter((chapter) => chapter && typeof chapter.title === 'string' && isAnnouncementTitle(chapter.title));
  const announcedOrders = new Set(announcements.map((chapter) => chapter.order));
  const body = announcedOrders.size ? catalog.filter((chapter) => !announcedOrders.has(chapter.order)) : catalog;
  if (announcements.length) {
    warnings.push(issue('catalog_announcement',
      `Skipped ${announcements.length} non-story catalog entr${announcements.length === 1 ? 'y' : 'ies'} (author note/appendix/announcement), e.g. "${announcements[0]!.title}"`));
  }
  if (catalog.length && !body.length) issues.push(issue('catalog_empty', 'Catalog has no chapter entries'));

  const orders = new Set<number>();
  const urls = new Set<string>();
  const titles = new Map<string, number>();
  const numbers = new Map<string, number>();
  const numberedEntries: Array<{ order: number; number: number; part: string; volume: string }> = [];
  const duplicateNumberOrders = new Set<number>();
  const volumeStarts: number[] = [];
  const explicitVolumes = new Set<string>();
  let inferredRestarts = 0;
  let currentVolume = '';
  let currentVolumeNumbered = 0;
  let volumeSerial = 0;
  let previousNumber: number | undefined;
  let previousOrder: number | undefined;
  let orderGaps = 0;
  for (const [index, chapter] of body.entries()) {
    if (!chapter || !Number.isSafeInteger(chapter.order) || chapter.order < 1 || typeof chapter.title !== 'string' || !chapter.title.trim() ||
        typeof chapter.url !== 'string' || !/^https?:\/\//u.test(chapter.url)) {
      issues.push(issue('missing_identity', `Catalog entry ${index + 1} is malformed`));
      continue;
    }
    if (previousOrder !== undefined) {
      if (chapter.order <= previousOrder) issues.push(issue('catalog_order_gap', `Catalog order ${chapter.order} does not follow ${previousOrder}`, chapter.order));
      else if (chapter.order > previousOrder + 1) {
        // A hole is explained by announcement entries that sat in it; only the
        // unexplained remainder is a hidden-TOC-entry gap.
        const skipped = announcements.filter((entry) => entry.order > previousOrder! && entry.order < chapter.order).length;
        if (chapter.order - previousOrder - 1 > skipped) orderGaps++;
      }
    }
    previousOrder = chapter.order;
    if (orders.has(chapter.order)) issues.push(issue('catalog_duplicate_order', `Duplicate catalog order ${chapter.order}`, chapter.order));
    orders.add(chapter.order);
    if (urls.has(chapter.url)) issues.push(issue('catalog_duplicate_url', `Duplicate catalog URL at order ${chapter.order}`, chapter.order));
    urls.add(chapter.url);

    const number = chapterNumberOf(chapter.title);
    const label = volumeLabel(chapter.title);
    if (/第\s*0+\s*[回章节卷篇]/u.test(chapter.title)) {
      regressionCount++;
      numberIssues.push(issue('catalog_number_regression', 'Chapter number 0 is not a valid positive chapter number', chapter.order));
    }
    if (label && label !== currentVolume) {
      // An explicit "volume + chapter" prefix is direct evidence that a
      // chapter-number reset belongs to a new volume, not a mixed catalog.
      currentVolume = label;
      volumeSerial++;
      explicitVolumes.add(label);
      currentVolumeNumbered = 0;
      previousNumber = undefined;
      volumeStarts.push(chapter.order);
    } else if (!label && number !== null && previousNumber !== undefined && number === 1 &&
      previousNumber >= 2 && currentVolumeNumbered >= 2) {
      // Some sources drop the volume heading but retain the complete 1..N
      // sequence for every volume. Treat a clean reset to 1 as a volume
      // boundary; one unlabelled reset alone is still rejected below.
      currentVolume = `__inferred_${volumeSerial + 1}`;
      volumeSerial++;
      inferredRestarts++;
      currentVolumeNumbered = 0;
      previousNumber = undefined;
      volumeStarts.push(chapter.order);
    }
    if (!currentVolume) {
      currentVolume = '__volume_1';
      volumeSerial = 1;
    }

    const normalized = normalizedTitle(chapter.title);
    const titleKey = `${currentVolume}|${normalized}`;
    if (titles.has(titleKey)) issues.push(issue('catalog_duplicate_title', `Duplicate chapter title "${chapter.title}" (orders ${titles.get(titleKey)} and ${chapter.order})`, chapter.order));
    else titles.set(titleKey, chapter.order);
    if (number !== null) {
      const part = chapterPart(chapter.title);
      numberedEntries.push({ order: chapter.order, number, part, volume: currentVolume });
      const numberKey = `${currentVolume}|${number}|${part}`;
      if (numbers.has(numberKey)) { duplicateNumberCount++; duplicateNumberOrders.add(chapter.order); numberIssues.push(issue('catalog_duplicate_number', `Duplicate chapter number ${number}${part ? `（${part}）` : ''} at orders ${numbers.get(numberKey)} and ${chapter.order}`, chapter.order)); }
      else numbers.set(numberKey, chapter.order);
      if (!input.options?.allowNonMonotonicNumbers && previousNumber !== undefined && number < previousNumber) {
        regressionCount++;
        numberIssues.push(issue('catalog_number_regression', `Chapter number ${number} follows ${previousNumber}`, chapter.order));
      }
      previousNumber = number;
      currentVolumeNumbered++;
    }
  }
  const volumeAware = explicitVolumes.size >= 1 || inferredRestarts >= 2;
  if (!volumeAware && volumeStarts.length) {
    for (const order of volumeStarts) numberIssues.push(issue('catalog_number_regression', 'Chapter numbering restarts without enough volume evidence', order));
    regressionCount += volumeStarts.length;
  }
  if (!volumeAware) {
    // Without enough volume evidence, fall back to whole-catalog uniqueness so
    // a concatenated duplicate edition cannot hide behind an inferred restart.
    const globalNumbers = new Map<string, number>();
    for (const entry of numberedEntries) {
      const key = `${entry.number}|${entry.part}`;
      if (globalNumbers.has(key)) {
        if (!duplicateNumberOrders.has(entry.order)) {
          duplicateNumberCount++;
          duplicateNumberOrders.add(entry.order);
          numberIssues.push(issue('catalog_duplicate_number', `Duplicate chapter number ${entry.number}${entry.part ? `（${entry.part}）` : ''} at orders ${globalNumbers.get(key)} and ${entry.order}`, entry.order));
        }
      } else globalNumbers.set(key, entry.order);
    }
    const globalTitles = new Map<string, number>();
    for (const chapter of body) {
      if (!chapter || typeof chapter.title !== 'string') continue;
      const key = normalizedTitle(chapter.title);
      if (globalTitles.has(key)) {
        issues.push(issue('catalog_duplicate_title', `Duplicate chapter title "${chapter.title}" (orders ${globalTitles.get(key)} and ${chapter.order})`, chapter.order));
      } else globalTitles.set(key, chapter.order);
    }
  }
  // so-novel's `order` may skip hidden TOC entries. A gap is a metadata warning
  // for long catalogs; a decreasing/duplicate sequence is still a blocking error.
  if (orderGaps > 0) {
    const gapIssue = issue('catalog_order_gap', `Catalog order skips ${orderGaps} number(s), likely hidden TOC entries`);
    if (body.length >= 50) warnings.push(gapIssue); else issues.push(gapIssue);
  }
  if (volumeAware && volumeStarts.length) {
    warnings.push(issue('catalog_volume_restart', `Recognized ${volumeStarts.length} volume restart(s); chapter numbers are scoped per volume`, volumeStarts[0]));
  }
  // An inserted extra entry shifts all later 第X回 numbers by one. A constant
  // offset (e.g. a preface before chapter one) is allowed. A jump between two
  // adjacent numbered chapters is evidence that two listings or editions were
  // concatenated; the same jump across an unnumbered entry (a 番外/卷末 marker
  // the source keeps in the TOC) is expected and is not held against the book.
  // Per-volume numbering legitimately changes the global offset, so skip this
  // check once multiple volumes were recognized.
  if ((!volumeAware || volumeSerial <= 1) && numberedEntries.length >= Math.max(1, Math.floor(body.length * 0.6))) {
    let previousOffset: number | undefined;
    let previousNumbered: { order: number; number: number } | undefined;
    let sawUnnumbered = false;
    for (const [index, chapter] of body.entries()) {
      if (!chapter || typeof chapter.title !== 'string') { sawUnnumbered = true; continue; }
      const number = chapterNumberOf(chapter.title);
      if (number === null) { sawUnnumbered = true; continue; }
      // Compare the position among chapter entries, not the raw TOC order:
      // announcement entries were already removed, so raw order would drift
      // by one for every announcement.
      const offset = index + 1 - number;
      if (previousOffset !== undefined && offset !== previousOffset && !sawUnnumbered && previousNumbered) {
        orderNumberMismatch = true;
        numberIssues.push(issue('catalog_number_order_mismatch',
          `Chapter order and number drift apart (order ${previousNumbered.order} has 第${previousNumbered.number}回, order ${chapter.order} has 第${number}回)`, chapter.order));
        break;
      }
      previousOffset = offset;
      previousNumbered = { order: chapter.order, number };
      sawUnnumbered = false;
    }
  }

  // Small numbers of misnumbered title labels (e.g. three chapters labelled
  // 第一百章) are common upstream OCR/export typos. They are accepted only when
  // the identity checks are clean and the anomalies are a small fraction of a
  // long catalog; URL/order/title checks and every text/page check still apply.
  const identityClean = !issues.some((item) => ['catalog_duplicate_url', 'catalog_duplicate_title', 'catalog_duplicate_order',
    'catalog_empty', 'catalog_too_large', 'missing_identity'].includes(item.code));
  const anomalyCount = duplicateNumberCount + regressionCount + (orderNumberMismatch ? 1 : 0);
  // Long serials from these sources often carry many mislabelled chapter
  // numbers while the actual reading order and URLs stay unique. Keep the
  // strict 5% budget for ordinary books, and a 20% budget for 1,000+ chapter
  // catalogs; 192-entry mixed editions (about 47% duplicates) still fail.
  const anomalyRatio = numberedEntries.length >= 1000 ? 0.20 : 0.05;
  const relaxed = body.length >= 50 && numberedEntries.length >= 50 && anomalyCount > 0 &&
    anomalyCount <= Math.max(3, Math.floor(numberedEntries.length * anomalyRatio)) && identityClean;
  if (relaxed) warnings.push(...numberIssues);
  else issues.push(...numberIssues);

  if (input.catalogAfter && !sameCatalog(catalog, input.catalogAfter)) {
    issues.push(issue('catalog_changed', 'Catalog changed between download and validation; retry to get one consistent snapshot'));
  }
  if (input.catalogOnly) {
    return { complete: issues.length === 0, issues, warnings, chapters: [], totalChars: 0 };
  }

  const files = Array.isArray(input.files) ? input.files : [];
  const byOrder = new Map<number, DownloadChapterFile>();
  for (const file of files) {
    // The downloader also fetches announcement pages; their text is never part
    // of the book, so they are neither missing nor unexpected chapters.
    if (file && announcedOrders.has(file.order)) continue;
    if (!file || !Number.isSafeInteger(file.order) || file.order < 1 || typeof file.text !== 'string') {
      issues.push(issue('unexpected_chapter_file', 'Malformed chapter file'));
      continue;
    }
    if (byOrder.has(file.order)) issues.push(issue('duplicate_chapter_file', `Duplicate chapter file for order ${file.order}`, file.order));
    else byOrder.set(file.order, file);
    if (!orders.has(file.order)) issues.push(issue('unexpected_chapter_file', `Chapter file ${file.order} has no catalog entry`, file.order));
  }

  const bodies = new Map<string, number>();
  const chapters: Array<{ order: number; title: string; text: string }> = [];
  const tailTruncations: NovelIntegrityIssue[] = [];
  const emptyChapters: NovelIntegrityIssue[] = [];
  for (const chapter of [...body].sort((a, b) => a.order - b.order)) {
    const file = byOrder.get(chapter.order);
    if (!file) {
      issues.push(issue('missing_chapter', `Chapter ${chapter.order} "${chapter.title}" was not downloaded`, chapter.order));
      continue;
    }
    const chapterBody = stripTrailingPunctuationArtifact(stripLeadingTitle(file.text, chapter.title));
    const chars = Array.from(chapterBody).length;
    if (chars === 0) {
      emptyChapters.push(issue('empty_chapter', `Chapter ${chapter.order} is empty`, chapter.order));
      // Keep the catalog heading with no invented body; a single such chapter
      // can be accepted as a visible warning under the user-approved policy.
      chapters.push({ order: chapter.order, title: chapter.title, text: '' });
      continue;
    }
    if (chars < minChapterChars) issues.push(issue('short_chapter', `Chapter ${chapter.order} has only ${chars} characters`, chapter.order));
    const normalizedBody = chapterBody.replace(/\s+/g, '');
    if (PLACEHOLDER.test(normalizedBody)) issues.push(issue('placeholder_chapter', `Chapter ${chapter.order} contains a placeholder page`, chapter.order));
    if (STRONG_PAGINATION.test(normalizedBody) || PAGE_COUNTER.test(normalizedBody) || NEXT_PAGE_WORD.test(chapterBody.slice(-200))) {
      issues.push(issue('missing_page_marker', `Chapter ${chapter.order} ends with a next-page marker; later pages are missing`, chapter.order));
    }
    if (TRUNCATING_TAIL.test(chapterBody.trimEnd())) {
      tailTruncations.push(issue('truncated_chapter_tail', `Chapter ${chapter.order} ends with a punctuation that suggests a cut sentence`, chapter.order));
    }
    if (chars >= 200) {
      const digest = hashText(normalizedBody);
      const previous = bodies.get(digest);
      if (previous !== undefined) issues.push(issue('duplicate_chapter_body', `Chapter ${chapter.order} repeats chapter ${previous}`, chapter.order));
      else bodies.set(digest, chapter.order);
    }
    chapters.push({ order: chapter.order, title: chapter.title, text: chapterBody });
  }

  // Check for title/number mismatches even when every file exists: a file whose
  // name disagrees with the catalog is evidence of a mixed or stale snapshot.
  for (const file of files) {
    if (announcedOrders.has(file.order)) continue;
    const catalogChapter = body.find((chapter) => chapter.order === file.order);
    if (catalogChapter && file.title && normalizedTitle(file.title) !== normalizedTitle(catalogChapter.title)) {
      // Some sources return a replacement character in the TOC title while the
      // chapter page itself is intact. That is a source encoding defect, not a
      // mixed edition; keep it visible as a warning instead of rejecting.
      if (catalogChapter.title.includes('\uFFFD')) warnings.push(issue('catalog_title_encoding', `Catalog title for order ${file.order} contained a replacement character; the downloaded title was kept`, file.order));
      else if (isTitleAlias(catalogChapter.title, file.title)) warnings.push(issue('catalog_title_alias', `Chapter file ${file.order} uses an equivalent title spelling; kept the catalog title`, file.order));
      else issues.push(issue('unexpected_chapter_file', `Chapter file ${file.order} title does not match the catalog`, file.order));
    }
  }

  if (emptyChapters.length === 1 && issues.length === 0 && body.length >= 20) {
    const only = emptyChapters[0]!;
    warnings.push({ ...only, code: 'source_empty_chapter', message: `${only.message}; the source page has no body, so only its heading is kept` });
  } else issues.push(...emptyChapters);

  // The tail rule is a heuristic, not proof of a missing page. Keep one
  // isolated source-side cut as a recorded warning so a known-damaged chapter
  // does not reject an otherwise complete edition; two or more still block.
  if (tailTruncations.length === 1 && issues.length === 0) warnings.push({ ...tailTruncations[0]!, message: `${tailTruncations[0]!.message}; the source page itself ends here` });
  else issues.push(...tailTruncations);

  const totalChars = chapters.reduce((sum, chapter) => sum + Array.from(chapter.text).length, 0);
  return { complete: issues.length === 0, issues, warnings, chapters: issues.length === 0 ? chapters : [], totalChars };
}

/** The first non-empty line is the engine-rendered chapter title; drop it for body checks. */
/** Drop final lines that are only punctuation, copied script, or source ads. */
export function stripTrailingPunctuationArtifact(text: string): string {
  const lines = text.split(/\r?\n/u);
  const noise = /^\s*(?:radb1\(\);|[\p{P}\p{S}\s]+|.*(?:先定个小目标|天才一秒记住|一秒记住本站|手机版阅读网址|笔趣阁手机版|请记住本站|百度搜索|最新网址|最新章节|书客居|推荐.{0,20}(?:新书|小说)|如果您中途有事离开|CTRL\+D|收藏夹|正在手打中|正在更新中|客官请稍等|求月票|双倍月票|#x[0-9a-f]{2,};|https?:\/\/|\/book_\d+\/).*)$/iu;
  // Some sources append their own JavaScript instead of an HTML footer. Only
  // trailing technical lines are removed; the story text before them is kept.
  const script = /^\s*(?:[{}();]+|[=+*/.]|[a-zA-Z_$][\w$.]*\s*(?:[=+\-*/]|\()|(?:var|let|const|function|if|else|return|for|while|document|window)\b)/u;
  while (lines.length) {
    const last = lines.at(-1)!;
    if (!noise.test(last) && !script.test(last)) break;
    lines.pop();
  }
  return lines.join('\n').trimEnd();
}

export function stripLeadingTitle(text: string, expectedTitle: string): string {
  const normalized = text.replace(/\r\n?/g, '\n').replace(/^\uFEFF/u, '').trimStart();
  const firstBreak = normalized.indexOf('\n');
  if (firstBreak >= 0) {
    const first = normalized.slice(0, firstBreak).trim();
    if (first === expectedTitle.trim() || normalizedTitle(first) === normalizedTitle(expectedTitle) || /^第[零〇一二两三四五六七八九十百千万\d]+[回章节卷篇]/u.test(first)) {
      return normalized.slice(firstBreak + 1).trim();
    }
  }
  return normalized.trim();
}

function hashText(text: string): string {
  // Small FNV-1a-style digest is enough to detect duplicated bodies without
  // pulling node:crypto into this pure module.
  let hash = 2166136261;
  for (let index = 0; index < text.length; index++) {
    hash ^= text.charCodeAt(index);
    hash = Math.imul(hash, 16777619) >>> 0;
  }
  return `${text.length}:${hash.toString(16)}`;
}

/** Compose the validated chapters into the TXT that the existing import pipeline accepts. */
export function composeValidatedText(book: Pick<NovelIdentity, 'title' | 'author'>, chapters: Array<{ order: number; title: string; text: string }>): string {
  const header = `书名：${book.title}\n作者：${book.author}\n`;
  const body = chapters.map((chapter) => `# ${chapter.title}\n\n${chapter.text}`).join('\n\n');
  return `${header}\n\n${body}\n`;
}
