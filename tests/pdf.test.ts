import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { isProducerNoticePage, measureTextCoverage, parsePdf } from '../src/pdf.ts';
import { describeImportError } from '../src/import-errors.ts';
import { buildPdf } from './helpers/minimal-pdf.ts';
import { importFileBlob } from '../src/stream-import.ts';
import { loadPagedBook, PageCache } from '../src/paged-book.ts';

const fixture = (name: string) => new Uint8Array(readFileSync(join(import.meta.dirname, 'fixtures', name)));
const PROSE = 'She read the letter twice, then walked down to the harbour and watched the boats come in.';
const CREDIT_PAGE = [
  "Document generated by Anna's Archive around 2023-2024 as part of the DuXiu collection (https://annas-blog.org/duxiu-exclusive.html).",
  'Images have been losslessly embedded.',
  '{"id": 1457, "action": "convert", "result_value": {"image_stats": "aa: 56"}, "pdg_main_pages_found": 280, "pdg_dir_name": "\\u00ed\\u2562"}',
].join('\n');

describe('PDF import', () => {
  it('extracts text, re-joins wrapped lines and keeps chapter headings', async () => {
    const book = await parsePdf(fixture('sample.pdf'));
    expect(book.chapters).toBe(3);
    expect(book.markdown).toContain('# 第一章 海边的信');
    expect(book.markdown).toContain('她坐在石阶上读完了第一行。');
    expect(book.markdown).not.toMatch(/^\s*1\s*$/m);
    expect(book.markdown).toContain('# 第三章 远方');
  });

  it('indexes the converted Markdown by chapter through the normal import pipeline', async () => {
    const book = await parsePdf(fixture('sample.pdf'));
    const dir = mkdtempSync(join(tmpdir(), 'bookfish-pdf-'));
    try {
      const source = join(dir, 'source.md');
      writeFileSync(source, book.markdown, 'utf8');
      const id = importFileBlob(dir, source, { filename: '样本.pdf', title: '测试小说', author: '' });
      const loaded = loadPagedBook(join(dir, `${id}.json.gz`), id, new PageCache());
      const chapters = [...new Set(loaded.segments.map((segment) => segment.chapter))];
      expect(chapters).toEqual(['第一章 海边的信', '第二章 回信', '第三章 远方']);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it('rejects PDFs without a text layer so scanned books never import empty', async () => {
    await expect(parsePdf(fixture('blank.pdf'))).rejects.toThrow(/text layer|OCR/);
  });

  it('rejects a scanned book whose only text layer is the packager credit page', async () => {
    // The DuXiu/Anna's Archive shape: hundreds of image pages, one credit page.
    const scan = buildPdf(['', '', '', '', '', CREDIT_PAGE]);
    await expect(parsePdf(scan)).rejects.toThrow(/No text layer: only 1 of 6 pages/u);
    expect(measureTextCoverage(['', '', '', '', '', CREDIT_PAGE])).toEqual({ pages: 6, textPages: 1, noticePages: 1, ratio: 0 });
  });

  it('judges coverage per page instead of by total characters', async () => {
    const almostScan = buildPdf([PROSE, '', '', '', '']);
    await expect(parsePdf(almostScan)).rejects.toThrow(/only 1 of 5 pages/u);
    expect(measureTextCoverage([PROSE, '', '', '', ''])).toEqual({ pages: 5, textPages: 1, noticePages: 0, ratio: 0.2 });
  });

  it('keeps importing text PDFs that have some blank or scanned pages', async () => {
    const book = await parsePdf(buildPdf([PROSE, '', PROSE, '', PROSE]));
    expect(book.markdown).toContain('She read the letter twice');
  });

  it('drops the credit page instead of importing it as prose', async () => {
    const book = await parsePdf(buildPdf([PROSE, PROSE, PROSE, PROSE, CREDIT_PAGE]));
    expect(book.markdown).toContain('She read the letter twice');
    expect(book.markdown).not.toContain('pdg_dir_name');
    expect(book.markdown).not.toContain("Document generated by Anna's Archive");
    expect(measureTextCoverage([PROSE, CREDIT_PAGE]).noticePages).toBe(1);
  });

  it('leaves ordinary prose that mentions an archive alone', () => {
    expect(isProducerNoticePage(PROSE)).toBe(false);
    expect(isProducerNoticePage('她查到《读秀》里收录过这份手稿，便托人去超星图书馆借阅。')).toBe(false);
    expect(isProducerNoticePage(CREDIT_PAGE)).toBe(true);
  });

  it('explains a scanned PDF rejection in plain language', async () => {
    const say = (zh: string, english: string) => zh;
    const message = describeImportError('No text layer: only 1 of 335 pages have selectable text; this is a scanned PDF (OCR it first, or import TXT/EPUB)', say);
    expect(message).toContain('335 页里只有 1 页有文字');
    expect(message).toContain('OCR');
    expect(describeImportError('PDF has no readable chapters', say)).toBe('PDF has no readable chapters');
    expect(say('中文', 'english')).toBe('中文');
  });

  it('rejects files that are not PDF documents', async () => {
    await expect(parsePdf(new Uint8Array(Buffer.from('not a pdf')))).rejects.toThrow();
  });
});
